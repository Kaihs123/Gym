function palFilter(q){
  var all=palAll();q=q.trim().toLowerCase();
  if(!q){
    var top=all.filter(function(x){return x.key.indexOf(":")<0});
    var rec=recents().map(function(k){return all.find(function(x){return x.key===k})}).filter(function(x){return x&&top.indexOf(x)<0}).slice(0,6);
    return top.concat(rec.map(function(x){return Object.assign({},x,{tag:"Recent"})}));
  }
  var toks=q.split(/\s+/);
  return all.map(function(x){
    var lab=x.label.toLowerCase(),hay=(x.label+" "+x.sub+" "+x.kw).toLowerCase(),sc=0;
    for(var i=0;i<toks.length;i++){var t=toks[i],ix=hay.indexOf(t);if(ix<0)return null;sc+=lab.indexOf(t)===0?4:(hay.indexOf(" "+t)>=0||ix===0?2:1)}
    if(lab.indexOf(q)===0)sc+=6;if(x.key.indexOf(":")<0)sc+=1;
    return{x:x,sc:sc};
  }).filter(Boolean).sort(function(a,b){return b.sc-a.sc}).slice(0,30).map(function(o){return o.x});
}
